import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { readerPopupPlacement, readerSentenceMarkup, readerSentenceTokens, shouldBecomeScroll } from '../ready/reader-learning-overlays.js';

const read=path=>readFileSync(path,'utf8');
const markup=readerSentenceMarkup({text:'The students had been waiting outside.'});
assert.match(markup,/data-reader-word/,'Reader text must expose immutable word anchors.');
assert.doesNotMatch(markup,/reader-inline-replacement|reader-inline-gloss/,'Reader text must not be replaced inline.');
assert.deepEqual(readerSentenceTokens('Take part in it.').map(item=>item.text),['Take','part','in','it']);
assert.equal(shouldBecomeScroll({distance:15}),true,'A drag must become scroll.');
assert.equal(shouldBecomeScroll({distance:0,scrollChanged:true}),true,'Native scroll movement must lock scroll ownership.');
assert.equal(shouldBecomeScroll({distance:4}),false,'Small stationary movement remains undecided.');
const top=readerPopupPlacement({left:120,width:50,top:200,bottom:220},{width:200,height:70});
assert.equal(top.placement,'top');assert.ok(top.x>=12&&top.caretX>=14);
const bottom=readerPopupPlacement({left:-10,width:20,top:4,bottom:24},{width:200,height:70});
assert.equal(bottom.placement,'bottom');assert.ok(bottom.x>=12);
const app=read('ready/app.js'),module=read('ready/reader-learning-overlays.js'),edge=read('server/ready/index.ts'),migration=read('supabase/migrations/20260902153000_ready_word_popup_senses_sentence_cache.sql'),baseCss=read('ready/learning-overlays-base.css'),build=read('tools/build-pages.mjs');
assert.match(app,/READER_INLINE_GLOSS_ENABLED===true[\s\S]*createReaderLearningOverlays/,'Learning overlay must remain feature-flagged.');
assert.match(module,/UNDECIDED[\s\S]*SCROLL[\s\S]*SENTENCE/,'Gesture ownership states must be explicit.');
assert.match(module,/shouldBecomeScroll[\s\S]*dismissWord/,'Scroll ownership must dismiss an open popup.');
assert.match(module,/data-word-anchor-active/,'Active word semantic hook is required.');
assert.match(module,/word-popup[\s\S]*wordPopupState/,'Word popup state hook is required.');
assert.match(module,/sentence-sheet-scrim[\s\S]*sentence-structure/,'Sentence sheet hooks are required.');
assert.match(baseCss,/position:fixed[\s\S]*pointer-events:auto/,'Popup must remain outside document flow.');
assert.match(baseCss,/sentence-sheet-scrim[\s\S]*touch-action:none/,'Scrim must own overlay input.');
assert.match(migration,/ready_saved_word_senses[\s\S]*unique \(saved_word_id, meaning_key\)/,'Senses must be normalized and unique.');
assert.match(migration,/ready_sentence_learning_cache/,'Sentence cache migration is required.');
assert.match(edge,/saveReaderWord[\s\S]*ready_saved_word_senses/,'Explicit add must append an idempotent sense.');
assert.match(edge,/removeReaderWord[\s\S]*\.delete\(\)\.eq\("student_id"/,'Whole lemma remove must delete the parent row.');
assert.match(edge,/sentenceEasyTranslation[\s\S]*sentenceStructure/,'Easy translation and lazy structure endpoints are required.');
assert.match(build,/reader-learning-overlays\.js/,'Pages build must include the new runtime.');
console.log('READY word popup, multi-sense, and sentence-sheet contracts verified');
